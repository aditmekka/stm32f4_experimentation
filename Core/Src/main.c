void pwm_setup(void) {
    __HAL_TIM_SET_PRESCALER(&htim1, 0);
    __HAL_TIM_SET_AUTORELOAD(&htim1, 1679); //100Khz -> 168MHz / 100KHz = 1680
    __HAL_TIM_SET_PRESCALER(&htim3, 0);
    __HAL_TIM_SET_AUTORELOAD(&htim3, 4199); //20kHz -> 84MHz / 20kHz = 4200

    HAL_TIM_PWM_Start(&htim1, TIM_CHANNEL_1);
    HAL_TIMEx_PWMN_Start(&htim1, TIM_CHANNEL_1);

    HAL_TIM_PWM_Start(&htim3, TIM_CHANNEL_1);
    HAL_TIM_PWM_Start(&htim3, TIM_CHANNEL_2);
    HAL_TIM_PWM_Start(&htim3, TIM_CHANNEL_3);
    HAL_TIM_PWM_Start(&htim3, TIM_CHANNEL_4);
}

void pwm_set_duty(PWMChannels_t channel, uint8_t duty) {
    if(duty < 0) duty = 0;
    if(duty > 100) duty = 100;

    uint16_t pulse;

    if(channel == PWM_ADV){
        pulse = (uint16_t)(duty * (__HAL_TIM_GET_AUTORELOAD(&htim1) + 1) / 100.0f);
    } else {
        pulse = (uint16_t)(duty * (__HAL_TIM_GET_AUTORELOAD(&htim3) + 1) / 100.0f);
    }
    
    switch (channel) {
        case MTRL_A:
            __HAL_TIM_SET_COMPARE(&htim3, TIM_CHANNEL_1, pulse);
            break;
        case MTRL_B:
            __HAL_TIM_SET_COMPARE(&htim3, TIM_CHANNEL_2, pulse);
            break;
        case MTRR_A:
            __HAL_TIM_SET_COMPARE(&htim3, TIM_CHANNEL_3, pulse);
            break;
        case MTRR_B:
            __HAL_TIM_SET_COMPARE(&htim3, TIM_CHANNEL_4, pulse);
            break;
        case PWM_ADV:
            __HAL_TIM_SET_COMPARE(&htim1, TIM_CHANNEL_1, pulse);
            break;
    }
}

